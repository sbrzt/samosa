# scripts/milestone.py

import shutil
import sys
from datetime import datetime
from pathlib import Path
from scripts.common import dump_yaml, load_yaml

STATUSES = ("draft", "tested", "aligned", "merged")  # in pipeline order
MILESTONES = Path("milestones")
TRACKED = ("iterations", "refactoring", "project", "prefixes.yaml", "ontology.yaml")
SKIP = shutil.ignore_patterns("docs", "__pycache__")  # project/docs is regenerated by `docs`


def rank(status):
    """Return the position of a status in `STATUSES`; unknown values count as draft."""
    return STATUSES.index(status) if status in STATUSES else 0


def status(it):
    """Return the `metadata.status` of an iteration directory."""
    return (load_yaml(it / "requirements.yaml").get("metadata") or {}).get("status") or "draft"


def snapshot(label):
    """Copy the project state into `milestones/<timestamp>-<label>/`.

    Copies `iterations/`, `refactoring/`, `project/` (without `docs/`),
    `prefixes.yaml` and `ontology.yaml`, whichever exist.

    Args:
        label: Suffix of the milestone name, e.g. `01-rights-tested`.

    Returns:
        The milestone directory.
    """
    dest = MILESTONES / f"{datetime.now():%Y%m%d-%H%M%S-%f}-{label}"
    dest.mkdir(parents=True)
    for name in TRACKED:
        src = Path(name)
        if src.is_dir():
            shutil.copytree(src, dest / name, ignore=SKIP)
        elif src.exists():
            shutil.copy2(src, dest / name)
    return dest


def promote(it, new_status):
    """Raise an iteration's status to `new_status` and record a milestone.

    The status never goes down: a passing `test` on a merged iteration leaves
    it merged. A milestone (see `snapshot`) is taken only when the status
    actually changes, i.e. at the end of a SAMOD step.

    Args:
        it: Iteration directory.
        new_status: One of `STATUSES`.
    """
    data = load_yaml(it / "requirements.yaml")
    meta = data["metadata"] = data.get("metadata") or {}
    if meta.get("status") in STATUSES and rank(meta["status"]) >= rank(new_status):
        return
    meta["status"] = new_status
    dump_yaml(data, it / "requirements.yaml")
    print(f"Status of {it.name}: {new_status}. Milestone: {snapshot(f'{it.name}-{new_status}')}")


def main(name: str = None):
    """List the milestones, or restore the project to one of them.

    Milestones are taken by `test`, `test --refactored` and `merge` whenever an
    iteration's status goes up. Restoring first takes a `before-restore`
    milestone of the current state, so it can be undone, then replaces
    `iterations/`, `refactoring/`, `project/`, `prefixes.yaml` and
    `ontology.yaml` with the milestone's copies. Run `docs` again afterwards.

    Args:
        name: Milestone directory name (or a unique part of it). If omitted,
            lists the milestones, oldest first.

    Raises:
        SystemExit: If no milestone or more than one matches `name`.
    """
    found = sorted(d for d in MILESTONES.glob("*") if d.is_dir()) if MILESTONES.exists() else []
    if not name:
        print("\n".join(d.name for d in found) or "No milestones yet.")
        return
    matches = [d for d in found if d.name == name] or [d for d in found if name in d.name]
    if len(matches) != 1:
        print(f"Error: {len(matches) or 'no'} milestones match '{name}'."
              + "".join(f"\n  {d.name}" for d in matches))
        sys.exit(1)
    source = matches[0]
    backup = snapshot("before-restore")
    for entry in TRACKED:
        target = Path(entry)
        if target.is_dir():
            docs = target / "docs"
            for item in target.iterdir():
                if item != docs:
                    shutil.rmtree(item) if item.is_dir() else item.unlink()
        elif target.exists():
            target.unlink()
        if (source / entry).is_dir():
            shutil.copytree(source / entry, target, dirs_exist_ok=True)
        elif (source / entry).exists():
            shutil.copy2(source / entry, target)
    print(f"Restored {source.name}. Previous state saved as {backup.name}.")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
